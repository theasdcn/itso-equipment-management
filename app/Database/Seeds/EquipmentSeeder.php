                echo "Exception inserting " . $item['name'] . ": " . $e->getMessage() . "\n";
            }
        }
        
        echo "Equipment seeder completed!\n";
        echo "Total items inserted: " . $inserted . "\n";
        echo "Errors: " . $errors . "\n";
    }
